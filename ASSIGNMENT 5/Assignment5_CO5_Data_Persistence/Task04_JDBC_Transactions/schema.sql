CREATE DATABASE IF NOT EXISTS assignment5;
USE assignment5;
CREATE TABLE IF NOT EXISTS bus_pass(pass_id VARCHAR(20) PRIMARY KEY,reg_no VARCHAR(30) NOT NULL,
 name VARCHAR(100) NOT NULL,route_no INT NOT NULL,amount DECIMAL(10,2) NOT NULL);
CREATE TABLE IF NOT EXISTS student(student_id INT AUTO_INCREMENT PRIMARY KEY,register_no VARCHAR(30) UNIQUE NOT NULL,
 name VARCHAR(100) NOT NULL,department VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS wallet(wallet_id INT PRIMARY KEY,balance DECIMAL(12,2) NOT NULL CHECK(balance>=0));
CREATE TABLE IF NOT EXISTS users(id VARCHAR(80) PRIMARY KEY,pwd_hash VARCHAR(255) NOT NULL);
